.ORIG x3000

MOV R6 #64
SHL R6 R6 #8

; Caso positivo: 8192 / 16384 = 0.5 -> 16384 en Q15
MOV R5 #32
SHL R5 R5 #8
OR R0 R5 R5
MOV R5 #64
SHL R5 R5 #8
OR R1 R5 R5
JSR CORDIC_DIV_NATIVE
STORE R0 0(R6)

; Caso negativo: -8192 / 16384 = -0.5 -> -16384
MOV R5 #-128
SHL R5 R5 #6
OR R0 R5 R5
MOV R5 #64
SHL R5 R5 #8
OR R1 R5 R5
JSR CORDIC_DIV_NATIVE
STORE R0 2(R6)

HALT

CORDIC_DIV_NATIVE
        AND R3 R3 R3
        CMP R0 R3
        BRN CORDIC_DIV_NEGATIVE
        SHL R0 R0 #1
        RET
CORDIC_DIV_NEGATIVE
        SUB R0 R3 R0
        SHL R0 R0 #1
        SUB R0 R3 R0
        RET

.END
